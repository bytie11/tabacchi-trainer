// --- Funzioni di utilità per il dataset ---

/**
 * Restituisce tutti i brand unici presenti nel dataset, ordinati alfabeticamente.
 */
export function getAllBrands(): string[] {
  const brands = new Set(products.map((p) => p.brand));
  return Array.from(brands).sort();
}

/**
 * Restituisce tutte le categorie effettivamente utilizzate nel dataset.
 */
export function getAllCategories(): ProductCategory[] {
  const categories = new Set(products.map((p) => p.category));
  return Array.from(categories) as ProductCategory[];
}

/**
 * Cerca un prodotto per id. Restituisce undefined se non trovato.
 */
export function getProductById(id: string): Product | undefined {
  return products.find((p) => p.id === id);
}
